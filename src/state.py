from typing import TypedDict, List, Literal

# ==============================================
# STATE DEFINITIONS FOR THE MULTI-AGENT SYSTEM
# ==============================================

class AgentState(TypedDict):
    """
    Represents the state of the multi-agent system at any given point in the workflow.
    """
    question: str                                       # Question asked by user
    plan: str                                           # Plan generated by the orchestrator agent
    routing: Literal["internal", "external", "hybrid"]  # Routing decision to determine which tools to use (internal manuals, external web, or hybrid)
    context: List[str]                                  # Contextual information retrieved from the knowledge base or web
    analysis: str                                       # Technical analysis and draft answer generated by the analyst agent
    critic: str                                         # Critique and feedback from the critic agent to detect hallucinations or missing information
    reflection: str                                     # Cause analysis and action plan generated by the self-reflection agent
    action_type: Literal["re_search", "re_write"]       # Type of action suggested by the self-reflection agent (re-execute search or re-write analysis)
    final_answer: str                                   # Final answer after critique and possible revision by the synthesizer agent
    is_valid: bool                                      # Indicates if the final answer is valid based on the critic's evaluation
    reflection_cycle: int                               # Counter for reflection cycles to avoid infinite loop (max reflection cycles)
