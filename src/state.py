from typing import TypedDict, List

class AgentState(TypedDict):
    question: str          # Question asked by user
    plan: str              # Plan generated by the orchestrator agent
    context: List[str]     # Contextual information retrieved by the researcher agent
    analysis: str          # Analysis and reasoning from the analyst agent
    critic: str            # Critique and feedback from the critic agent
    final_answer: str      # Final answer after critique and possible revision
    score: int             # Confidence score of the final answer (0-10)
    iteration: int         # Counter for loops to avoid infinite loop (max iterations)